#!/bin/bash
# 文件用途：第一个 Shell 脚本，演示 echo 输出、注释、变量使用与脚本执行方式对比
# 语法：bash 01-hello-shell.sh
# 场景：电商项目运维脚本入门，建立脚本运行直觉

# ============================================================
# 1. 最简单的输出
# ============================================================
echo "Hello, Shell!"
echo "欢迎进入电商项目运维脚本世界"

# ============================================================
# 2. 注释的使用
# ============================================================
# 这是单行注释，从 # 到行末都是注释
PROJECT="ecommerce"   # 行尾也可以写注释
# Shell 没有原生多行注释，如需大段注释可用 :<<'EOF' ... EOF 包裹（不推荐滥用）

# ============================================================
# 3. 变量基础使用
# ============================================================
PROJECT="ecommerce"          # 自定义变量，等号两边不能有空格
VERSION="2.4"
DEPLOY_DIR="/opt/ecommerce"

echo "项目名称：$PROJECT"
echo "项目版本：${VERSION}"      # 花括号界定变量边界，推荐
echo "部署目录：${DEPLOY_DIR}"

# 单引号 vs 双引号
echo '单引号：$PROJECT 不被解析'      # 原样输出
echo "双引号：$PROJECT 被解析"        # 替换为变量值

# 命令替换：把命令输出赋值给变量
TODAY=$(date +%F)             # 推荐写法 $()
HOST=$(hostname)
echo "今天日期：$TODAY"
echo "主机名：$HOST"

# ============================================================
# 4. 三种执行方式对比说明
# ============================================================
# 方式一：bash script.sh（无需可执行权限，新开子 Shell）
#   bash 01-hello-shell.sh
#
# 方式二：chmod +x script.sh && ./script.sh（需可执行权限，新开子 Shell）
#   chmod +x 01-hello-shell.sh
#   ./01-hello-shell.sh
#
# 方式三：source script.sh 或 . script.sh（在当前 Shell 中执行，影响当前环境）
#   source 01-hello-shell.sh
#   . 01-hello-shell.sh
#
# 区别演示：本脚本里 export 一个变量，用 bash 执行后当前 Shell 拿不到，
#         用 source 执行后当前 Shell 能拿到。

export APP_NAME="ecommerce-prod"
echo "脚本内 APP_NAME = $APP_NAME"

# ============================================================
# 5. 输出脚本自身信息
# ============================================================
echo "脚本名：$0"
echo "当前 Shell PID：$$"
echo "脚本执行完毕，退出码：$?"
