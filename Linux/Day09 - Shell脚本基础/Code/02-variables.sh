#!/bin/bash
# 文件用途：变量练习——自定义变量、环境变量、位置参数、单引号vs双引号、readonly、unset、特殊变量
# 语法：bash 02-variables.sh nginx mysql redis
# 场景：电商项目接收服务名作为参数，演示各种变量用法

# ============================================================
# 1. 自定义变量
# ============================================================
APP="ecommerce"
ENV="production"
LOG_DIR="/opt/ecommerce/logs"

echo "=== 自定义变量 ==="
echo "应用：$APP"
echo "环境：$ENV"
echo "日志目录：${LOG_DIR}"

# ============================================================
# 2. 单引号 vs 双引号 vs 无引号
# ============================================================
echo ""
echo "=== 引号对比 ==="
SERVICE="nginx"
echo '单引号：服务是 $SERVICE'             # 不解析，原样输出
echo "双引号：服务是 $SERVICE"             # 解析变量
echo "双引号+命令替换：今天 $(date +%F)"    # 解析命令
echo 无引号：服务是 $SERVICE               # 无引号也可解析，但不能含空格

# ============================================================
# 3. 环境变量
# ============================================================
echo ""
echo "=== 环境变量 ==="
export DB_HOST="192.168.1.100"
export DB_PORT=3306

echo "DB_HOST = $DB_HOST"
echo "DB_PORT = $DB_PORT"
echo "PATH = $PATH"
echo "HOME = $HOME"
echo "USER = $USER"
echo "SHELL = $SHELL"

# 验证：env/printenv 查看环境变量
echo "（用 printenv 验证）DB_HOST = $(printenv DB_HOST)"

# ============================================================
# 4. 只读变量
# ============================================================
echo ""
echo "=== 只读变量 ==="
readonly APP="ecommerce"      # 标记为只读
declare -r MAX_CONN=100       # 等价写法
echo "APP（只读）= $APP"
echo "MAX_CONN（只读）= $MAX_CONN"
# APP="new"   # 取消注释会报错：bash: APP: readonly variable

# ============================================================
# 5. 变量删除
# ============================================================
echo ""
echo "=== 变量删除 ==="
TEMP_VAR="hello-shell"
echo "删除前：TEMP_VAR = $TEMP_VAR"
unset TEMP_VAR
echo "删除后：TEMP_VAR = $TEMP_VAR（空）"

# ============================================================
# 6. 位置参数变量
# ============================================================
echo ""
echo "=== 位置参数 ==="
echo "脚本名 \$0：$0"
echo "脚本短名：${0##*/}        # 用 \${0##*/} 去掉路径只留文件名"
echo "第一个参数 \$1：$1"
echo "第二个参数 \$2：$2"
echo "第三个参数 \$3：$3"
echo "参数个数 \$#：$#"
echo "所有参数 \$@：$@"
echo "所有参数 \$*：$*"

# ============================================================
# 7. $@ vs $* 在循环中的区别（经典面试题）
# ============================================================
echo ""
echo "=== \$@ vs \$* 在循环中的区别 ==="
echo "--- 遍历 \"\$@\"（每个参数独立）---"
for arg in "$@"; do
    echo "  [$arg]"
done

echo "--- 遍历 \"\$*\"（合并为一个字符串）---"
for arg in "$*"; do
    echo "  [$arg]"
done

# ============================================================
# 8. 特殊变量
# ============================================================
echo ""
echo "=== 特殊变量 ==="
echo "当前 Shell PID \$\$：$$"
echo "上条命令退出码 \$?：$?"

# 演示 $! 最近后台进程 PID
sleep 1 &
echo "后台进程 PID \$!：$!"
wait    # 等待后台进程结束，避免影响后续输出

# 演示 $_ 上一条命令的最后一个参数
ls /opt/ecommerce 2>/dev/null || true
echo "上一条命令最后一个参数 \$_：$_"

# 演示 $? 退出码
true
echo "执行 true 后 \$?：$?"
false
echo "执行 false 后 \$?：$?"

echo ""
echo "变量练习完毕。"
