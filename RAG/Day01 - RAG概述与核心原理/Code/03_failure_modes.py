# -*- coding: utf-8 -*-
"""
文件用途：Day01 - 03 RAG 失败模式诊断（无代码演练）
通过"问题样例 + 失败现象 + 诊断结论"的形式，训练你识别 RAG 系统
最常见的质量瓶颈。不调用任何外部服务，纯知识卡片。

运行：python 03_failure_modes.py （仅打印诊断矩阵，无需联网）
"""

# 每条：(失败模式, 典型问题示例, 失败现象, 根本原因, 对应解决Day)
FAILURE_CASES = [
    (
        "句法不匹配",
        "伙计，出差回来咋报销？",
        "检索不到出差报销文档",
        "口语化提问与文档书面语向量距离远",
        "查询改写 / HyDE（Day07）",
    ),
    (
        "语义鸿沟",
        "咱们哪天可以不上班？",
        "召回到年假/放假，而非远程办公",
        "问题与文档表达层面不同",
        "语义切块 + HyDE（Day04/07）",
    ),
    (
        "切块不当",
        "报销标准是多少？（标准分散在多块）",
        "只召回部分标准，回答不完整",
        "一句话被切成多块，语义断裂",
        "切块策略 / 父块检索（Day03/09）",
    ),
    (
        "TopK 过小",
        "列出全部支付方式",
        "只召回前 2 块，漏掉部分信息",
        "similarity_top_k 设置过小",
        "参数调优（Day05）",
    ),
    (
        "缺乏重排",
        "多相似文档谁最相关？",
        "Top1 不是最相关的那个",
        "向量召回按相似度而非按意图",
        "重排 Reranking（Day06）",
    ),
    (
        "生成幻觉",
        "文档没提，模型却补充细节",
        "回答出现原文没有的内容",
        "生成未受约束 / 忠实性不足",
        "忠实性评估 + 约束 Prompt（Day10）",
    ),
]


def main() -> None:
    print("=" * 70)
    print("RAG 失败模式诊断矩阵（DataIQ 场景）")
    print("=" * 70)
    for i, (mode, example, symptom, cause, solve) in enumerate(FAILURE_CASES, 1):
        print(f"\n[{i}] {mode}")
        print(f"    问题示例：{example}")
        print(f"    失败现象：{symptom}")
        print(f"    根本原因：{cause}")
        print(f"    对应解决：{solve}")

    print("\n" + "=" * 70)
    print("诊断方法论")
    print("=" * 70)
    print("遇到 RAG 答错时的排查顺序（自下而上）：")
    print("  1. 检索层：召回的相关度够吗？（先看召回结果再怪模型）")
    print("  2. 生成层：召回对了，模型用对了吗？（是否有幻觉/答非所问）")
    print("  3. 端到端：整体流程哪里最弱？（用评估指标量化，见 Day10）")
    print("  4. 原则：先分层定位，再针对性优化，切忌盲目调参。")


if __name__ == "__main__":
    main()