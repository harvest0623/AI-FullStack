# ============================================================
# 1. 单行注释：以 # 开头，本行不会被解释器执行
# ============================================================

"""
这是多行注释（使用三引号字符串），
通常用于描述模块、类、函数的用途。
"""

# ============================================================
# 2. 缩进：Python 用缩进表示代码块，约定使用 4 个空格
# ============================================================
def check_stock(stock: int) -> str:
    """根据库存数量返回状态描述。"""
    if stock > 0:
        # 同一代码块必须保持相同缩进
        return "有货"
    else:
        return "缺货"


# ============================================================
# 3. 多行语句：使用反斜杠 \ 或括号 () 换行
# ============================================================
# 方式一：反斜杠续行
total = 100 + \
        200 + \
        300
# 方式二：括号内换行（推荐，更安全）
product_info = (
    "商品ID: 1001, "
    "名称: iPhone 15, "
    "价格: 5999"
)
print("多行语句结果：", total, product_info, sep="\n")

# ============================================================
# 4. 多变量赋值
# ============================================================
# 同时给多个变量赋值（元组解包）
product_id, product_name, price = 1001, "iPhone 15", 5999
# 链式赋值（同一值赋给多个变量）
a = b = c = 0
# 变量交换（无需中间变量）
x, y = 1, 2
x, y = y, x
print(f"交换后 x={x}, y={y}")

# ============================================================
# 5. print 的 sep 与 end 参数
# ============================================================
# sep：分隔多个参数
print("ID", "名称", "价格", sep="->")
# end：行末字符，默认 \n
for i in range(3):
    print(f"第{i}个商品", end=" | ")
print()  # 换行收尾

# ============================================================
# 6. 一行写多条语句（用分号分隔，不推荐滥用）
# ============================================================
p = 5999; q = 10; print(f"总价：{p * q}")

# ============================================================
# 7. import this：展示 The Zen of Python
# ============================================================
# import this 会打印 Python 之禅，是理解 Python 设计哲学的最佳方式
import this

# ============================================================
# 8. 模块入口：if __name__ == '__main__'
# ============================================================
if __name__ == "__main__":
    print("\n--- eshop 基础语法演示结束 ---")
    print("check_stock(50) =>", check_stock(50))
    print("check_stock(0) =>", check_stock(0))
