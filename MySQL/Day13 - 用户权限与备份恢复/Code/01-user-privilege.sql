-- ------------------------------------------------------------
-- 0. 清理可能存在的旧账号与角色（保证可重复执行）
--     注意：DROP USER 不存在会报错，所以先查再删
-- ------------------------------------------------------------
DROP USER IF EXISTS 'app_user'@'localhost';
DROP USER IF EXISTS 'app_user'@'192.168.1.%';
DROP USER IF EXISTS 'read_only'@'%';
DROP USER IF EXISTS 'analyst'@'%';
DROP USER IF EXISTS 'dba_admin'@'localhost';
DROP USER IF EXISTS 'backup_user'@'localhost';
DROP USER IF EXISTS 'repl_user'@'192.168.%.%';
DROP USER IF EXISTS 'app01'@'%';
DROP USER IF EXISTS 'analyst01'@'%';
DROP USER IF EXISTS 'dba01'@'%';

DROP ROLE IF EXISTS 'role_app';
DROP ROLE IF EXISTS 'role_reader';
DROP ROLE IF EXISTS 'role_dba';
DROP ROLE IF EXISTS 'role_backup';

-- ============================================================
-- 1. 用户管理：创建、修改密码、重命名、删除
-- ============================================================

-- ------------------------------------------------------------
-- 1.1 创建应用账号（本地连接）
--     密码需满足 validate_password 策略（默认 MEDIUM）：
--     至少 8 位、含大小写、含数字、含特殊字符
-- ------------------------------------------------------------
CREATE USER 'app_user'@'localhost' IDENTIFIED BY 'App@123456';

-- ------------------------------------------------------------
-- 1.2 创建只读账号（任意主机可连接，生产慎用 %）
-- ------------------------------------------------------------
CREATE USER 'read_only'@'%' IDENTIFIED BY 'Read@123456';

-- ------------------------------------------------------------
-- 1.3 修改用户密码
-- ------------------------------------------------------------
ALTER USER 'app_user'@'localhost' IDENTIFIED BY 'App@NewPass789';

-- ------------------------------------------------------------
-- 1.4 重命名用户（同时改变主机）
-- ------------------------------------------------------------
RENAME USER 'app_user'@'localhost' TO 'app_user'@'192.168.1.%';

-- ------------------------------------------------------------
-- 1.5 查看当前所有用户
-- ------------------------------------------------------------
SELECT user, host, account_locked FROM mysql.user ORDER BY user, host;

-- ============================================================
-- 2. 权限授予 GRANT
-- ============================================================

-- ------------------------------------------------------------
-- 2.1 给应用账号授予 ecommerce 库的 CRUD 权限
--     不给 DDL（CREATE/DROP/ALTER），符合最小权限原则
-- ------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON ecommerce.* TO 'app_user'@'192.168.1.%';

-- ------------------------------------------------------------
-- 2.2 给只读账号授予 ecommerce 库的 SELECT 与 SHOW VIEW
-- ------------------------------------------------------------
GRANT SELECT, SHOW VIEW ON ecommerce.* TO 'read_only'@'%';

-- ------------------------------------------------------------
-- 2.3 创建分析账号，仅授予 products 表的 SELECT，且只暴露部分列
--     演示列级权限
-- ------------------------------------------------------------
CREATE USER 'analyst'@'%' IDENTIFIED BY 'Analyst@123';
GRANT SELECT (id, name, price, status) ON ecommerce.products TO 'analyst'@'%';

-- ------------------------------------------------------------
-- 2.4 创建 DBA 账号（仅本地连接），授予全局所有权限 + GRANT OPTION
-- ------------------------------------------------------------
CREATE USER 'dba_admin'@'localhost' IDENTIFIED BY 'Dba@123456';
GRANT ALL PRIVILEGES ON *.* TO 'dba_admin'@'localhost' WITH GRANT OPTION;

-- ============================================================
-- 3. SHOW GRANTS 查看权限
-- ============================================================

-- ------------------------------------------------------------
-- 3.1 查看应用账号权限
-- ------------------------------------------------------------
SHOW GRANTS FOR 'app_user'@'192.168.1.%';

-- ------------------------------------------------------------
-- 3.2 查看只读账号权限
-- ------------------------------------------------------------
SHOW GRANTS FOR 'read_only'@'%';

-- ------------------------------------------------------------
-- 3.3 查看分析账号的列级权限
-- ------------------------------------------------------------
SHOW GRANTS FOR 'analyst'@'%';

-- ------------------------------------------------------------
-- 3.4 查看 DBA 权限
-- ------------------------------------------------------------
SHOW GRANTS FOR 'dba_admin'@'localhost';

-- ------------------------------------------------------------
-- 3.5 查看当前连接用户的权限
-- ------------------------------------------------------------
SHOW GRANTS;

-- ============================================================
-- 4. REVOKE 撤销权限
-- ============================================================

-- ------------------------------------------------------------
-- 4.1 业务变更：应用账号不再需要 DELETE 权限
--     撤销 DELETE
-- ------------------------------------------------------------
REVOKE DELETE ON ecommerce.* FROM 'app_user'@'192.168.1.%';
SHOW GRANTS FOR 'app_user'@'192.168.1.%';

-- ------------------------------------------------------------
-- 4.2 进一步收紧：应用账号也不再需要 UPDATE
-- ------------------------------------------------------------
REVOKE UPDATE ON ecommerce.* FROM 'app_user'@'192.168.1.%';
SHOW GRANTS FOR 'app_user'@'192.168.1.%';

-- ============================================================
-- 5. 角色机制（MySQL 8）
-- ============================================================

-- ------------------------------------------------------------
-- 5.1 创建三个角色
--     角色本质是"权限模板"，本身不能登录
-- ------------------------------------------------------------
CREATE ROLE 'role_app', 'role_reader', 'role_dba';

-- ------------------------------------------------------------
-- 5.2 给角色授权（语法同用户）
-- ------------------------------------------------------------
-- 应用角色：CRUD（不含 DELETE，更安全）
GRANT SELECT, INSERT, UPDATE ON ecommerce.* TO 'role_app';

-- 只读角色：SELECT + SHOW VIEW
GRANT SELECT, SHOW VIEW ON ecommerce.* TO 'role_reader';

-- DBA 角色：全局所有权限
GRANT ALL PRIVILEGES ON *.* TO 'role_dba';

-- ------------------------------------------------------------
-- 5.3 创建用户并把角色授予用户
-- ------------------------------------------------------------
CREATE USER 'app01'@'%'      IDENTIFIED BY 'App01@123456';
CREATE USER 'analyst01'@'%'  IDENTIFIED BY 'Analyst01@123456';
CREATE USER 'dba01'@'%'      IDENTIFIED BY 'Dba01@123456';

GRANT 'role_app'    TO 'app01'@'%';
GRANT 'role_reader' TO 'analyst01'@'%';
GRANT 'role_dba'    TO 'dba01'@'%';

-- ------------------------------------------------------------
-- 5.4 设置默认角色（用户连接后自动激活）
--     否则用户连接后角色未激活，需手动 SET ROLE
-- ------------------------------------------------------------
SET DEFAULT ROLE 'role_app'    TO 'app01'@'%';
SET DEFAULT ROLE 'role_reader' TO 'analyst01'@'%';
SET DEFAULT ROLE 'role_dba'    TO 'dba01'@'%';

-- ------------------------------------------------------------
-- 5.5 查看角色权限与用户有效权限
-- ------------------------------------------------------------
-- 查看角色本身的权限
SHOW GRANTS FOR 'role_app';
SHOW GRANTS FOR 'role_reader';
SHOW GRANTS FOR 'role_dba';

-- 查看用户直接权限（不含角色）
SHOW GRANTS FOR 'app01'@'%';

-- 查看用户含角色后的有效权限（USING 关键字）
SHOW GRANTS FOR 'app01'@'%' USING 'role_app';
SHOW GRANTS FOR 'analyst01'@'%' USING 'role_reader';
SHOW GRANTS FOR 'dba01'@'%' USING 'role_dba';

