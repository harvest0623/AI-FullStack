-- ============================================================
-- 6. 最小权限实践：备份账号与从库账号
-- ============================================================

-- ------------------------------------------------------------
-- 6.1 备份专用账号
--     mysqldump 所需权限：
--     - SELECT：读数据
--     - RELOAD：FLUSH TABLES
--     - LOCK TABLES：锁表（--single-transaction 时可不锁）
--     - REPLICATION CLIENT：查看 master 状态
--     - SHOW VIEW：备份视图定义
--     - EVENT：备份事件
--     - TRIGGER：备份触发器
-- ------------------------------------------------------------
CREATE USER 'backup_user'@'localhost' IDENTIFIED BY 'Backup@123456';
GRANT SELECT, RELOAD, LOCK TABLES, REPLICATION CLIENT, SHOW VIEW, EVENT, TRIGGER
ON *.* TO 'backup_user'@'localhost';

SHOW GRANTS FOR 'backup_user'@'localhost';

-- ------------------------------------------------------------
-- 6.2 从库复制账号
--     主库上创建，仅给 REPLICATION SLAVE 权限
--     从库用此账号拉取 binlog
-- ------------------------------------------------------------
CREATE USER 'repl_user'@'192.168.%.%' IDENTIFIED BY 'Repl@123456';
GRANT REPLICATION SLAVE ON *.* TO 'repl_user'@'192.168.%.%';

SHOW GRANTS FOR 'repl_user'@'192.168.%.%';

-- ============================================================
-- 7. 资源限制（可选）
-- ============================================================

-- ------------------------------------------------------------
-- 7.1 限制 app01 每小时最多 1000 次连接、最多 50000 次查询
--     防止应用异常拖垮数据库
-- ------------------------------------------------------------
ALTER USER 'app01'@'%'
    WITH MAX_CONNECTIONS_PER_HOUR 1000
         MAX_QUERIES_PER_HOUR 50000;

-- 查看资源限制
SELECT user, host,
       max_questions AS 每小时最大查询,
       max_connections AS 每小时最大连接
FROM mysql.user
WHERE user IN ('app01', 'analyst01', 'dba01');

-- ============================================================
-- 8. 账号锁定与解锁（MySQL 8）
-- ============================================================

-- ------------------------------------------------------------
-- 8.1 临时锁定账号（不删除，禁止登录）
-- ------------------------------------------------------------
ALTER USER 'analyst01'@'%' ACCOUNT LOCK;

-- 查看锁定状态
SELECT user, host, account_locked FROM mysql.user
WHERE user = 'analyst01';

-- 解锁
ALTER USER 'analyst01'@'%' ACCOUNT UNLOCK;

