# -*- coding: utf-8 -*-
"""
Day01 - 02 虚拟机 vs 容器

对比传统虚拟化（Hypervisor + 虚拟机）与容器化（Docker）的区别，
理解容器为何"轻量、秒级启动、共享内核"。

离线可运行。
"""


def contrast():
    print("虚拟化对比：虚拟机 vs 容器\n")
    print("""             ┌──────────── 虚拟机 ────────────┐
             │  App   │  App   │（每个含完整 GuOS） │
             │ GuestOS │  GuestOS │                   │
             │  Hypervisor（虚拟化层）              │
             │        Host OS + 硬件                │
             └──────────────────────────────────────┘
       每个虚拟机：自带完整操作系统 → 重、慢、启动分钟级

             ┌──────────── 容器（Docker）────────────┐
             │ App │ App │ App │（共享内核，无 GuOS）│
             │      容器运行时 / Host OS / 硬件        │
             └──────────────────────────────────────┘
       每个容器：只打包应用环境，共享宿主机内核 → 轻、秒级
    """)


def table():
    rows = [
        ("隔离级别", "硬件级（完整 OS）", "进程级（共享内核）"),
        ("启动速度", "分钟级", "秒级"),
        ("体积", "GB 级（含整个 OS）", "MB 级（只有应用+依赖）"),
        ("资源占用", "高", "低，共享内核"),
        ("可移植性", "依赖同构 OS", "一次构建到处运行"),
        ("适合", "强隔离/多 OS", "微服务、CI、快速部署"),
    ]
    print(f"{'维度':<12}{'虚拟机':<22}{'容器'}")
    print("-" * 62)
    for a, b, c in rows:
        print(f"{a:<12}{b:<22}{c}")


def main():
    print(">> 容器 vs 虚拟机\n")
    contrast()
    print("核心差异表：\n")
    table()
    print("\n  tips: 容器「轻」的原因是共享宿主机内核；也因此容器内不能用与宿主不同的内核。")


if __name__ == "__main__":
    main()