"""
Day01 - 03 典型场景与能力边界

工具调用适合什么、不适合什么，以及常见应用场景。

离线可运行（纯讲解）。
"""


def scenarios():
    print("典型应用场景：\n")
    rows = [
        ("实时查询", "天气、新闻、股票、数据库查询"),
        ("执行操作", "发消息、写文件、下单、改配置"),
        ("获取上下文", "读文档、查日志、搜百科"),
        ("多步任务", "订机票（查→选→订）、多轮研究"),
        ("工具编排", "作为 Agent 的能力底座"),
    ]
    for k, v in rows:
        print(f"  · {k:<8}{v}")


def suitable():
    print("\n适合工具调用的判断：\n")
    print("  ✓ 需要外部/实时数据（模型训练数据够不着）")
    print("  ✓ 需要真正『做』一件事（有副作用）")
    print("  ✓ 结果能确定性地由函数产出（而非由模型编造）")
    print("  ✓ 需要把外部状态写回业务系统")


def not_suitable():
    print("\n不适合或要小心的场景：\n")
    rows = [
        ("纯知识问答", "模型已掌握的知识直接回答即可，不必调工具"),
        ("不可逆危险操作", "删库/转大额——必须人工确认"),
        ("依赖返回才继续", "可以用，但要多轮循环并设终止"),
        ("参数不明确", "工具定义模糊会导致模型瞎填参数"),
    ]
    for k, v in rows:
        print(f"  · {k:<12}{v}")


def main():
    print(">> 工具调用场景与边界\n")
    scenarios()
    suitable()
    not_suitable()
    print("\n  tips: 原则——『能确定性算出的外部能力』最适合做成工具。")


if __name__ == "__main__":
    main()